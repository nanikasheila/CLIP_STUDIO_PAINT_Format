"""Make crates/csp-assets/src/subtool/columns.rs: the SQLite type CSP
declares for every Variant column (from docs/assets/spec/subtool-columns.tsv),
so that a .sut written from settings declares its columns as CSP does.

    python tools/assets/subtool_column_types.py docs/assets/spec/subtool-columns.tsv crates/csp-assets/src/subtool/columns.rs
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path


def main(tsv: str, out: str) -> None:
    rows = list(csv.DictReader(Path(tsv).open(encoding="utf-8"), delimiter="\t"))
    types = sorted({(row["column"], row["type"]) for row in rows})
    lines = [
        "//! Generated by `tools/assets/subtool_column_types.py` from",
        "//! `docs/assets/spec/subtool-columns.tsv`; do not edit.",
        "",
        "/// `Variant` columns and the SQLite type CSP declares them with, sorted by name.",
        "pub(crate) const VARIANT_COLUMN_TYPES: &[(&str, &str)] = &[",
    ]
    lines += [f'    ("{name}", "{kind}"),' for name, kind in types]
    lines += ["];", ""]
    Path(out).write_text("\n".join(lines), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main(*sys.argv[1:3])
